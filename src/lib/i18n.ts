const dicts: Record<Lang, Dict> = { fr, en }

export function translator(lang: Lang) {
  return (key: string) => dicts[lang][key] ?? dicts.fr[key] ?? key
}

const DAYS_FR = ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi']
const DAYS_EN = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
const MONTHS_FR = [
  'janvier',
  'février',
  'mars',
  'avril',
  'mai',
  'juin',
  'juillet',
  'août',
  'septembre',
  'octobre',
  'novembre',
  'décembre',
]
const MONTHS_EN = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
]

export function formatDay(iso: string, lang: Lang) {
  const d = new Date(iso + 'T12:00:00')
  const day = lang === 'fr' ? DAYS_FR[d.getDay()] : DAYS_EN[d.getDay()]
  const month = lang === 'fr' ? MONTHS_FR[d.getMonth()] : MONTHS_EN[d.getMonth()]
  return lang === 'fr' ? `${day} ${d.getDate()} ${month}` : `${day} ${month} ${d.getDate()}`
}
